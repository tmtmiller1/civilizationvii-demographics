// Generate ui/screen-demographics/styles/screen-demographics-locale-fonts.css from the mod's other
// stylesheets.
//   node scripts/gen-locale-fonts.mjs          write the file
//   node scripts/gen-locale-fonts.mjs --check  exit 1 when the file is missing or out of date
//
// Every rule that sets a font list without a CJK face gets a copy per CJK locale, prefixed with that
// locale's <html> class (set by applyLocaleFontClass in ui/core/demographics-i18n.js), carrying the
// locale's font list. BodyFont, TitleFont, TitilliumWeb and the generic families have no Hangul, kana
// or Han glyphs, so without the copies Chinese, Japanese and Korean text in those elements renders as
// missing-glyph boxes. A rule led by another face (monospace) keeps it first and gains the CJK faces
// after it, so its Latin look survives.
// GameFace ignores var() inside font-family and its CSSOM cannot rewrite rules, so the locale
// lists are spelled out here, in the order the game uses (global-scaling.js getOrderedFontFamily).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const stylesDir = path.join(root, "ui/screen-demographics/styles");
const OUT_NAME = "screen-demographics-locale-fonts.css";
const out = path.join(stylesDir, OUT_NAME);

const LOCALES = [
  { cls: "dg-lang-sc", slot: 1 },
  { cls: "dg-lang-tc", slot: 2 },
  { cls: "dg-lang-jp", slot: 3 },
  { cls: "dg-lang-kr", slot: 4 }
];

/** @param {string} base @param {number} slot @returns {string} */
function fontList(base, slot) {
  const faces = [base, base + "-SC", base + "-TC", base + "-JP", base + "-KR"];
  [faces[0], faces[slot]] = [faces[slot], faces[0]];
  return faces.join(", ") + ", sans-serif";
}

/**
 * @param {string} family A rule's font-family value.
 * @returns {string|null} "title", "body", "keep:<list>" for another leading face, or null when the rule
 *   needs no copy (inherit, or already lists a CJK face).
 */
function kindOf(family) {
  const fam = family.trim().replace(/["']/g, "");
  if (/^(inherit|initial|unset)$/i.test(fam) || /-(SC|TC|JP|KR)\b/.test(fam)) return null;
  const first = fam.split(",")[0].trim();
  if (first === "TitleFont") return "title";
  if (first === "BodyFont" || first === "TitilliumWeb" || /^(sans-serif|serif)$/i.test(first)) return "body";
  return "keep:" + fam;
}

/** @returns {Record<string, string[]>} Selectors per font kind, in file order. */
function collect() {
  /** @type {Record<string, string[]>} */
  const sel = { title: [], body: [] };
  const files = fs.readdirSync(stylesDir).filter((f) => f.endsWith(".css") && f !== OUT_NAME).sort();
  for (const f of files) {
    const css = fs.readFileSync(path.join(stylesDir, f), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
    for (const m of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
      const fam = /font-family\s*:\s*([^;]+)/.exec(m[2]);
      const kind = fam && kindOf(fam[1]);
      if (!kind) continue;
      for (const s of m[1].split(",").map((x) => x.trim()).filter(Boolean)) {
        if (s.startsWith("@") || /^(html|:root)\b/.test(s)) throw new Error(`${f}: cannot prefix selector "${s}"`);
        if (!sel[kind]) sel[kind] = [];
        if (!sel[kind].includes(s)) sel[kind].push(s);
      }
    }
  }
  return sel;
}

/** @returns {string} The generated stylesheet. */
function build() {
  const sel = collect();
  const lines = [
    "/* screen-demographics-locale-fonts.css",
    "   GENERATED by scripts/gen-locale-fonts.mjs from the other stylesheets in this folder; do not edit.",
    "   Chinese, Japanese and Korean font lists for every rule whose own list has no CJK face, keyed on",
    "   the <html> class set by applyLocaleFontClass(). */",
    ""
  ];
  for (const { cls, slot } of LOCALES) {
    for (const kind of Object.keys(sel)) {
      if (!sel[kind].length) continue;
      const list = kind === "title" ? fontList("TitleFont", slot)
        : kind === "body" ? fontList("BodyFont", slot)
          : kind.slice(5) + ", " + fontList("BodyFont", slot);
      lines.push(sel[kind].map((s) => `html.${cls} ${s}`).join(",\n") + " {");
      lines.push(`    font-family: ${list};`);
      lines.push("}", "");
    }
  }
  return lines.join("\n");
}

const css = build();
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (cur !== css) {
    console.log(`gen-locale-fonts: ${OUT_NAME} is out of date; run node scripts/gen-locale-fonts.mjs`);
    process.exit(1);
  }
  console.log(`gen-locale-fonts: ${OUT_NAME} up to date`);
} else {
  fs.writeFileSync(out, css);
  console.log(`gen-locale-fonts: wrote ${OUT_NAME}`);
}
